/** Block scalars with blank lines of every width around their content. */
export function blockScalarGrid(): string[] {
  const texts: string[] = []
  for (const chomp of ['', '-', '+']) {
    for (const content of [1, 2, 3]) {
      for (const first of [0, 1, 2, 4]) {
        for (const last of [0, 1, 2, 3, 4, 5]) {
          const pad = (n: number) => ' '.repeat(n)
          texts.push(
            `a: |${chomp}\n${pad(first)}\n${pad(content)}x\n${pad(last)}\n${pad(first + last)}`,
          )
          texts.push(`a: |${chomp}\n${pad(content)}x\n${pad(last)}\n${pad(first)}\nb: 1`)
          texts.push(
            `a: |${content}${chomp}\n${pad(content + 3)}x\n${pad(last)}\n${pad(first)}\nb: 1`,
          )
          texts.push(
            `a: |${content}${chomp}\n${pad(first)}\n${pad(content + 3)}x\n${pad(last)}\n${pad(first)}\nb: 1`,
          )
        }
      }
    }
  }
  return texts
}

