export function largeTexts(): string[] {
  const nodes = Array.from(
    { length: 120 },
    (_, i) =>
      `{"id":"n${i}","x":${i * 7},"y":${-i},"width":160,"height":90,"type":"text","text":"node ${i}"}`,
  )
  const edges = Array.from(
    { length: 160 },
    (_, i) => `{"id":"e${i}","fromNode":"n${i % 120}","toNode":"n${(i * 7) % 120}"}`,
  )
  const facets = Object.fromEntries(
    Array.from({ length: 120 }, (_, i) => [`p${i % 5}.k${i}/v${i}`, { n: i, s: `v${i}` }]),
  )
  return [
    `{"nodes":[${nodes.join(',')}],"edges":[${edges.join(',')}]}`,
    `{"nodes":[${nodes.join(',')}],"edges":[${edges.join(',')},{"id":"e0","fromNode":"n0","toNode":"n1"}]}`,
    `{"x-whiteboard":{"facets":${JSON.stringify(facets)}}}`,
  ]
}

