// Dumps the vendored BudouX Japanese model as the Rust tables the phrase
// breaker in crates/core/canvas-render reads (ADR-0054 step 7).
//
//   node packages/canvas-render/scripts/gen-budoux-model.mjs <model.rs>          write the tables
//   node packages/canvas-render/scripts/gen-budoux-model.mjs --check <model.rs>  fail when the committed tables differ
//
// The destination is the caller's, not the script's: a shipped source naming the
// Rust tree would make every crate change rerun this package's dependents.
//
// Each feature group becomes one static array of (key, weight) sorted by the
// key's UTF-16 units, so the Rust side is a binary search over slices. A key is
// kept as units rather than a string: a lookup window can end inside a
// surrogate pair, and that half must stay representable. The script runs while
// the TypeScript model exists; after that the committed tables are the
// specification.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const MODEL = fileURLToPath(new URL('../src/vendor/budoux/ja-model.ts', import.meta.url))
const GROUPS = [
  'UW1',
  'UW2',
  'UW3',
  'UW4',
  'UW5',
  'UW6',
  'BW1',
  'BW2',
  'BW3',
  'TW1',
  'TW2',
  'TW3',
  'TW4',
]
const PER_LINE = 3

const unitsOf = (key) => Array.from({ length: key.length }, (_, i) => key.charCodeAt(i))
const compareUnits = (a, b) => {
  for (let i = 0; i < Math.min(a.length, b.length); i += 1) if (a[i] !== b[i]) return a[i] - b[i]
  return a.length - b.length
}
const hex = (unit) => `0x${unit.toString(16).padStart(4, '0')}`

function entriesOf(weights) {
  return Object.entries(weights)
    .map(([key, weight]) => {
      if (!Number.isInteger(weight))
        throw new RangeError(`weight ${weight} of ${key} is not an integer`)
      return { units: unitsOf(key), weight }
    })
    .sort((a, b) => compareUnits(a.units, b.units))
}

function groupText(name, entries) {
  const cells = entries.map(({ units, weight }) => `(&[${units.map(hex).join(', ')}], ${weight})`)
  const rows = []
  for (let i = 0; i < cells.length; i += PER_LINE) {
    rows.push(`    ${cells.slice(i, i + PER_LINE).join(', ')},`)
  }
  return [
    '#[rustfmt::skip]',
    `pub(super) static ${name}: [Entry; ${entries.length}] = [`,
    ...rows,
    '];',
    '',
  ]
}

async function generate() {
  const { jaModel } = await import(MODEL)
  const unknown = Object.keys(jaModel).filter((group) => !GROUPS.includes(group))
  if (unknown.length > 0)
    throw new RangeError(`feature groups ${unknown} are not scored by the parser`)
  const entries = GROUPS.map((name) => [name, entriesOf(jaModel[name] ?? {})])
  const total = entries.flatMap(([, list]) => list).reduce((sum, { weight }) => sum + weight, 0)
  const count = entries.reduce((sum, [, list]) => sum + list.length, 0)
  return [
    '// @generated by `node packages/canvas-render/scripts/gen-budoux-model.mjs` from the vendored BudouX Japanese model. Edit the script, not this file.',
    '',
    '//! The `BudouX` Japanese model (`budoux@0.9.0`) as sorted tables: per feature group, the',
    '//! UTF-16 units of a key and its integer weight, ordered by those units.',
    '',
    '/// A key as UTF-16 units, and its weight.',
    "pub(super) type Entry = (&'static [u16], i32);",
    '',
    `/// The sum of every weight (${count} entries): a boundary needs twice its window's sum above this.`,
    `pub(super) const TOTAL: i64 = ${total};`,
    '',
    ...entries.flatMap(([name, list]) => groupText(name, list)),
  ].join('\n')
}

const args = process.argv.slice(2)
const check = args.includes('--check')
const out = args.find((arg) => arg !== '--check')
if (out === undefined) {
  process.stderr.write('usage: gen-budoux-model.mjs [--check] <model.rs>\n')
  process.exit(2)
}
const text = await generate()
if (check) {
  let committed = ''
  try {
    committed = readFileSync(out, 'utf8')
  } catch {}
  if (committed !== text) {
    process.stderr.write(
      `${out} differs from the tables the vendored BudouX model generates; run this script without --check\n`,
    )
    process.exit(1)
  }
} else {
  writeFileSync(out, text)
}
