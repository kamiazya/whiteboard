// Dumps css-line-break's class trie as the Rust table the line breaker in
// crates/core/canvas-render reads (ADR-0054 step 7).
//
//   node packages/canvas-render/scripts/gen-linebreak-table.mjs <table.rs>          write the table
//   node packages/canvas-render/scripts/gen-linebreak-table.mjs --check <table.rs>  fail when the committed table differs
//
// The destination is the caller's, not the script's: a shipped source naming the
// Rust tree would make every crate change rerun this package's dependents.
//
// The table is the trie walked over every code point U+0000-10FFFF and cut
// into runs of equal RAW value: the trie's own answer, letter-number flag
// (+50) included, because LB8a reads a raw ZWJ and the class pass reads the
// flag. Each run is one u32, `start << 8 | raw`, so the Rust side is a binary
// search over a flat array. The script runs while the TypeScript and its
// dependency still exist; after that the committed table is the specification.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const LAST_CODE_POINT = 0x10ffff
const PER_LINE = 8

/** The library's deep import: no `exports` map blocks it, and only it holds the trie. */
function loadTrie() {
  const manifest = require('css-line-break/package.json')
  const { UnicodeTrie } = require('css-line-break/dist/lib/LineBreak.js')
  return { version: manifest.version, get: (cp) => UnicodeTrie.get(cp) }
}

function runsOf(get) {
  const runs = []
  let previous = -1
  for (let cp = 0; cp <= LAST_CODE_POINT; cp += 1) {
    const raw = get(cp)
    if (raw !== previous) {
      if (raw < 0 || raw > 0xff) throw new RangeError(`raw value ${raw} at U+${cp.toString(16)}`)
      runs.push(cp * 256 + raw)
      previous = raw
    }
  }
  return runs
}

function generate() {
  const { version, get } = loadTrie()
  const runs = runsOf(get)
  const rows = []
  for (let i = 0; i < runs.length; i += PER_LINE) {
    const row = runs
      .slice(i, i + PER_LINE)
      .map((run) => {
        const hex = run.toString(16).padStart(8, '0')
        return `0x${hex.slice(0, 4)}_${hex.slice(4)}`
      })
      .join(', ')
    rows.push(`    ${row},`)
  }
  return [
    '// @generated by `node packages/canvas-render/scripts/gen-linebreak-table.mjs` from the trie of css-line-break. Edit the script, not this file.',
    '',
    `//! The line-break class of every code point, as \`css-line-break\` ${version} answers it.`,
    '',
    `/// The version of \`css-line-break\` whose trie this table was walked from.`,
    `pub const SOURCE_VERSION: &str = "${version}";`,
    '',
    '/// Runs of equal raw value over U+0000-10FFFF, each `start << 8 | raw`. A raw',
    '/// value above 50 carries the letter-number flag (class + 50).',
    `#[rustfmt::skip]`,
    `pub(super) static RUNS: [u32; ${runs.length}] = [`,
    ...rows,
    '];',
    '',
  ].join('\n')
}

const args = process.argv.slice(2)
const check = args.includes('--check')
const out = args.find((arg) => arg !== '--check')
if (out === undefined) {
  process.stderr.write('usage: gen-linebreak-table.mjs [--check] <table.rs>\n')
  process.exit(2)
}
const text = generate()
if (check) {
  let committed = ''
  try {
    committed = readFileSync(out, 'utf8')
  } catch {}
  if (committed !== text) {
    process.stderr.write(
      `${out} differs from the table css-line-break's trie generates; run this script without --check\n`,
    )
    process.exit(1)
  }
} else {
  writeFileSync(out, text)
}
