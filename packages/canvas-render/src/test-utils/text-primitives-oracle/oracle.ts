/**
 * The recorded answers of the text primitives (`uaxSegments`,
 * `longestFittingCount`, `fitToWidth` and the inline junction), which the Rust
 * port replays exactly (`crates/core/canvas-render/tests/text_primitives_oracle.rs`).
 * Every measurement is the fake measurer's, so a width is exact, and every
 * double is the hex of its IEEE bits. Small corpora are recorded string by
 * string; the large ones as one digest per chunk, regenerated by the Rust test
 * from the `meta` record.
 */

const MIXED = { seed: 0x7e47_0001, count: 20_000, chunk: 1000, minLen: 1, maxLen: 10 }
const FONT_COMBOS: readonly (readonly [number, number])[] = [
  [0.6, 12],
  [0.55, 13.5],
  [1, 16],
]
const GRAPHEME_CHUNK = 4096

const GRAPHEMES = new Intl.Segmenter('en', { granularity: 'grapheme' })

/** The UTF-16 end of every grapheme of `text`, as `Intl.Segmenter` cuts it. */
export function graphemeEnds(text: string): number[] {
  const ends: number[] = []
  for (const { index, segment } of GRAPHEMES.segment(text)) ends.push(index + segment.length)
  return ends
}

const bitsView = new DataView(new ArrayBuffer(8))
/** The next double below a positive finite one; zero stays zero. */
function nextDown(value: number): number {
  if (!(value > 0) || !Number.isFinite(value)) return value
  bitsView.setFloat64(0, value)
  bitsView.setBigUint64(0, bitsView.getBigUint64(0) - 1n)
  return bitsView.getFloat64(0)
}

const font = (sizePx: number): FontDescriptor => ({
  family: 'Inter',
  fallbackChain: [],
  weight: 400,
  style: 'normal',
  sizePx,
})

export interface FitRecord {
  kind: 'fit'
  t: string
  f: string
  s: string
  m: string
  r: string
  tr: boolean
  ov: boolean
  w: string
  calls: number[]
}

export interface FitAnswer {
  r: string
  tr: boolean
  ov: boolean
  w: string
  calls: number[]
}

/** `fitToWidth` over the fake measurer, with the length of every text it measured. */
export function fitAnswer(text: string, factor: number, size: number, max: number): FitAnswer {
  const calls: number[] = []
  const inner = createFakeMeasure(factor)
  const fitted = fitToWidth(
    text,
    font(size),
    (t, f) => {
      calls.push(t.length)
      return inner(t, f)
    },
    max,
  )
  const w = inner(fitted.text, font(size)).advanceWidth
  return {
    r: fitted.text,
    tr: fitted.truncated === true,
    ov: fitted.overflows === true,
    w: f64Hex(w),
    calls,
  }
}

/** The widths a text is fitted to: the unusable ones, and each edge of a few prefixes. */
function widthsFor(text: string, factor: number, size: number): number[] {
  const unit = factor * size
  const width = (n: number) => n * factor * size
  const ks =
    text.length <= 5
      ? range(1, text.length)
      : [1, 2, Math.floor(text.length / 2), text.length - 1, text.length]
  const widths = [0, -1, Number.NaN, Number.POSITIVE_INFINITY, 1e-9, unit / 2]
  for (const k of ks) widths.push(width(k), nextDown(width(k)))
  const seen = new Set<string>()
  return widths.filter((w) => !seen.has(f64Hex(w)) && seen.add(f64Hex(w)))
}

const range = (from: number, to: number): number[] =>
  Array.from({ length: Math.max(0, to - from + 1) }, (_, i) => from + i)

function fitRecords(): FitRecord[] {
  const records: FitRecord[] = []
  for (const [i, [, text]] of TEXTS.entries()) {
    for (const [c, [factor, size]] of FONT_COMBOS.entries()) {
      if (c > 0 && i % 3 !== c) continue
      for (const max of widthsFor(text, factor, size)) {
        records.push({
          kind: 'fit',
          t: text,
          f: f64Hex(factor),
          s: f64Hex(size),
          m: f64Hex(max),
          ...fitAnswer(text, factor, size, max),
        })
      }
    }
  }
  return records
}

export interface UaxRecord {
  kind: 'uax'
  t: string
  s: string[]
  e: number[]
}

/** A text holding a lone surrogate, which only UTF-16 units can spell. */
interface UaxUnitsRecord {
  kind: 'uaxu'
  u: number[]
  e: number[]
}

const endsOf = (segments: readonly string[]): number[] => {
  let at = 0
  return segments.map((segment) => {
    at += segment.length
    return at
  })
}

const stringOfUnits = (u: readonly number[]): string => String.fromCharCode(...u)

function uaxRecords(): (UaxRecord | UaxUnitsRecord)[] {
  const texts = [...TEXTS.map(([, t]) => t), ...UAX_EXTRA]
  const wellFormed = texts.map((t): UaxRecord => {
    const s = [...uaxSegments(t)]
    return { kind: 'uax', t, s, e: endsOf(s) }
  })
  const lone = UAX_LONE.map(
    (u): UaxUnitsRecord => ({
      kind: 'uaxu',
      u: [...u],
      e: endsOf(uaxSegments(stringOfUnits(u))),
    }),
  )
  return [...wellFormed, ...lone]
}

export interface GraphemeRecord {
  kind: 'grapheme'
  t: string
  g: number[]
}

export interface LongestRecord {
  kind: 'longest'
  limit: number
  guess: number
  threshold: number
  r: number
  p: number[]
}

export function longestAnswer(limit: number, guess: number, threshold: number) {
  const p: number[] = []
  const r = longestFittingCount(
    (n) => {
      p.push(n)
      return n <= threshold
    },
    limit,
    guess,
  )
  return { p, r }
}

export interface DigestRecord {
  kind: 'digest'
  c: string
  k: number
  n: number
  h: number
}

interface MetaRecord {
  kind: 'meta'
  mixed: typeof MIXED
  alphabet: number[]
  combos: [string, string][]
  graphemeReps: number[]
  longestLimits: number
}

const LONGEST_LIMITS = 64

const units = (text: string): number[] =>
  Array.from({ length: text.length }, (_, i) => text.charCodeAt(i))

function feedFit(digest: Digest, answer: FitAnswer): void {
  for (const u of units(answer.r)) digest.feed(u)
  digest.feed((answer.tr ? 1 : 0) | (answer.ov ? 2 : 0))
  for (const c of answer.calls) digest.feed(c)
  digest.feed(0xffff_ffff)
}

const mixedAlphabet = (): number[] => [...MIXED_ALPHABET, ...MIXED_ASTRAL, ...MIXED_JAMO]

/** The strings of mixed chunk `k` with the width each is fitted to. */
function* mixedFits(
  k: number,
): Generator<{ text: string; factor: number; size: number; max: number }> {
  const alpha = mixedAlphabet()
  const next = mulberry32(MIXED.seed + k)
  for (let i = 0; i < MIXED.chunk; i += 1) {
    const length = MIXED.minLen + (next() % (MIXED.maxLen - MIXED.minLen + 1))
    let text = ''
    for (let j = 0; j < length; j += 1)
      text += String.fromCodePoint(alpha[next() % alpha.length] ?? 0)
    const [factor, size] = FONT_COMBOS[next() % FONT_COMBOS.length] ?? [0.6, 12]
    const count = next() % (text.length + 2)
    const exact = count * factor * size
    const mode = next() % 3
    const max = mode === 0 ? exact : mode === 1 ? nextDown(exact) : exact + (factor * size) / 2
    yield { text, factor, size, max }
  }
}

function mixedDigests(): DigestRecord[] {
  const records: DigestRecord[] = []
  for (let k = 0; k < MIXED.count / MIXED.chunk; k += 1) {
    const digest = new Digest()
    for (const { text, factor, size, max } of mixedFits(k)) {
      feedFit(digest, fitAnswer(text, factor, size, max))
    }
    records.push({ kind: 'digest', c: 'fit-mixed', k, n: MIXED.chunk, h: digest.value })
  }
  return records
}

/**
 * Entries are joined by U+0000, a Control, which always breaks on both sides
 * (GB4, GB5): one segmenter pass over a chunk answers every entry in it, at a
 * sixth of the cost of a pass per entry.
 */
const SEPARATOR = '\u0000'

function feedJoined(digest: Digest, entries: readonly string[]): void {
  for (const end of graphemeEnds(entries.join(SEPARATOR))) digest.feed(end)
  digest.feed(0xffff_ffff)
}

const isSurrogate = (cp: number) => cp >= 0xd800 && cp <= 0xdfff

/** The context each code point of the census is segmented in. */
const CENSUS_SHAPES: readonly (readonly [string, (cp: string) => string])[] = [
  ['between', (cp) => `a${cp}a`],
  ['conjunct', (cp) => `\u0915\u094d${cp}`],
]

function graphemeDigests(): DigestRecord[] {
  const records: DigestRecord[] = []
  GRAPHEME_REPS.forEach((a, k) => {
    const digest = new Digest()
    const entries: string[] = []
    for (const b of GRAPHEME_REPS) {
      for (const c of GRAPHEME_REPS) entries.push(String.fromCodePoint(a, b, c))
    }
    feedJoined(digest, entries)
    records.push({ kind: 'digest', c: 'grapheme-triples', k, n: entries.length, h: digest.value })
  })
  for (const [name, shape] of CENSUS_SHAPES) {
    for (let k = 0; k <= 0x10ffff >> 12; k += 1) {
      const entries: string[] = []
      const last = Math.min(0x10ffff, k * GRAPHEME_CHUNK + GRAPHEME_CHUNK - 1)
      for (let cp = k * GRAPHEME_CHUNK; cp <= last; cp += 1) {
        if (!isSurrogate(cp)) entries.push(shape(String.fromCodePoint(cp)))
      }
      const digest = new Digest()
      feedJoined(digest, entries)
      records.push({
        kind: 'digest',
        c: `grapheme-census-${name}`,
        k,
        n: entries.length,
        h: digest.value,
      })
    }
  }
  return records
}

function longestRecords(): (LongestRecord | DigestRecord)[] {
  const records: (LongestRecord | DigestRecord)[] = []
  for (const limit of [0, 1, 2, 5, 17]) {
    for (const guess of [0, 1, 3, limit, limit + 2]) {
      for (const threshold of range(0, limit + 1)) {
        records.push({
          kind: 'longest',
          limit,
          guess,
          threshold,
          ...longestAnswer(limit, guess, threshold),
        })
      }
    }
  }
  for (const [limit, guess, threshold] of [
    [1_000_000, 1, 999_999],
    [1_000_000, 500_000, 3],
    [1_000_000, 1, 1_000_000],
  ] as const) {
    records.push({
      kind: 'longest',
      limit,
      guess,
      threshold,
      ...longestAnswer(limit, guess, threshold),
    })
  }
  for (let limit = 0; limit <= LONGEST_LIMITS; limit += 1) {
    const digest = new Digest()
    let n = 0
    for (let guess = 0; guess <= limit + 3; guess += 1) {
      for (let threshold = 0; threshold <= limit; threshold += 1) {
        const { p, r } = longestAnswer(limit, guess, threshold)
        for (const probe of p) digest.feed(probe)
        digest.feed(r)
        digest.feed(0xffff_ffff)
        n += 1
      }
    }
    records.push({ kind: 'digest', c: 'longest-sweep', k: limit, n, h: digest.value })
  }
  return records
}

export function recording(): unknown[] {
  const meta: MetaRecord = {
    kind: 'meta',
    mixed: MIXED,
    alphabet: mixedAlphabet(),
    combos: FONT_COMBOS.map(([f, s]) => [f64Hex(f), f64Hex(s)]),
    graphemeReps: [...GRAPHEME_REPS],
    longestLimits: LONGEST_LIMITS,
  }
  const graphemes: GraphemeRecord[] = TEXTS.map(([, t]) => ({
    kind: 'grapheme',
    t,
    g: graphemeEnds(t),
  }))
  return [
    meta,
    ...uaxRecords(),
    ...graphemes,
    ...longestRecords(),
    ...fitRecords(),
    ...edgeRecords(),
    ...junctionRecords(),
    ...mixedDigests(),
    ...graphemeDigests(),
  ]
}
