import { readFileSync, writeFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import {
  askedTexts,
  breaksOf,
  type DigestRecord,
  decidedEntries,
  modelEntries,
  type OracleRecord,
  phraseLengths,
  reach,
  recording,
  type TextRecord,
  unitsOfRecord,
} from '../test-utils/budoux-oracle/oracle.js'

/**
 * The committed recording of where the vendored BudouX parser (`budoux@0.9.0`,
 * Japanese model) cuts a text equals what the TypeScript answers today, and
 * the Rust port replays it exactly (`tests/budoux_oracle.rs` in
 * `crates/core/canvas-render`). Re-record after a deliberate change with
 * `WHITEBOARD_RECORD_ORACLE=1 pnpm vitest run --project canvas-render-node budoux-recorded`.
 * The Rust model tables the port reads are regenerated by `scripts/gen-budoux-model.mjs`
 * (its freshness is held in `tools/arch-lint`, since a test here may not read the Rust tree).
 */
const FILE = new URL('./budoux.jsonl', import.meta.url)

if (process.env.WHITEBOARD_RECORD_ORACLE === '1') {
  writeFileSync(
    FILE,
    `${recording()
      .map((r) => JSON.stringify(r))
      .join('\n')}\n`,
  )
}

describe('the recorded BudouX oracle', () => {
  const text = readFileSync(FILE, 'utf8')
  const recorded = text
    .trimEnd()
    .split('\n')
    .map((line) => JSON.parse(line) as OracleRecord)
  const texts = recorded.filter((r): r is TextRecord => r.kind === 'text')
  const digests = recorded.filter((r): r is DigestRecord => r.kind === 'digest')

  it('reaches every corpus and every chunk of the large ones', () => {
    const per = (c: string) => texts.filter((r) => r.c === c).length
    expect(per('real')).toBeGreaterThanOrEqual(30)
    expect(per('kana')).toBeGreaterThanOrEqual(10)
    expect(per('kanji')).toBeGreaterThanOrEqual(10)
    expect(per('scripts')).toBeGreaterThanOrEqual(20)
    expect(per('emoji')).toBeGreaterThanOrEqual(15)
    expect(per('entry')).toBe(modelEntries().length)
    expect(digests.filter((r) => r.c === 'prefixes')).toHaveLength(per('real'))
    expect(digests.filter((r) => r.c === 'stream')).toHaveLength(100)
  })

  it('records answers that cut somewhere and nowhere', () => {
    expect(texts.filter((r) => r.b.length > 0).length, 'texts with a boundary').toBeGreaterThan(
      texts.length / 2,
    )
    expect(texts.filter((r) => r.b.length === 0).length, 'and without').toBeGreaterThan(10)
    expect(texts.filter((r) => 'u' in r).length, 'texts holding a lone surrogate').toBeGreaterThan(
      5,
    )
  })

  it('looks every entry of the model up with a key that is present', () => {
    const entries = modelEntries().length
    expect(entries).toBe(1678)
    expect(reach(askedTexts(recorded, true)).size).toBe(entries)
    // What the corpora written by hand reach alone, without the strings built to aim at one entry.
    const byHand = recorded.filter((r): r is TextRecord => r.kind === 'text' && r.c !== 'entry')
    expect(reach(byHand.map(unitsOfRecord)).size).toBeGreaterThan(entries / 3)
  })

  it('aims a string at each entry that the entry alone decides', () => {
    expect(decidedEntries(recorded).size, 'entries whose sign moves their own string').toBe(
      modelEntries().length,
    )
  })

  it('records the corpora the builders produce today', () => {
    const lines = text.trimEnd().split('\n')
    const rebuilt = recording().map((r) => JSON.stringify(r))
    const parted = rebuilt.findIndex((line, i) => line !== lines[i])
    expect(
      parted === -1 ? undefined : rebuilt[parted]?.slice(0, 120),
      'the first record the TypeScript no longer answers as recorded',
    ).toBeUndefined()
    expect(rebuilt).toHaveLength(lines.length)
  })

  it('answers each recorded text with the boundaries the TypeScript gives it', () => {
    const parted = texts.find(
      (r) => JSON.stringify(breaksOf(unitsOfRecord(r))) !== JSON.stringify(r.b),
    )
    expect(parted, 'the first text answered differently').toBeUndefined()
  })

  it('splits a text into phrases whose lengths are the gaps between its boundaries', () => {
    for (const record of texts) {
      const units = unitsOfRecord(record)
      const cuts = [0, ...record.b, units.length]
      const gaps = cuts.slice(1).map((cut, i) => cut - (cuts[i] ?? 0))
      expect(phraseLengths(units), record.c).toEqual(units.length === 0 ? [] : gaps)
    }
  })
})
