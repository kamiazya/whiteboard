//! The two emitters, one walk of a checked contract each.
//!
//! What each construct means is written here side by side for both
//! languages: a bound is `.min()` in Zod and a check in the Rust type's
//! `Deserialize`; `refuse` is `z.strictObject` and `deny_unknown_fields`;
//! `strip` is `z.object` and no field; `keep` is `z.looseObject` and an
//! `extra` map; an optional field is `.optional()` and `Option<T>`.
//! The serde Rust half reads through `MapOnly` because serde's derived
//! `Deserialize` also accepts a JSON array in field order, which
//! `z.strictObject` refuses. A crate that may take no dependency gets plain
//! data types instead, and its named checks are hand-written predicates the
//! doc comments point at.
//!
//! The Rust text is unformatted; `mod.rs` runs it through rustfmt. The Zod
//! text is written in the shape biome keeps, and a line past biome's width
//! is refused rather than emitted.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use super::dialect::{
    Checked, CheckedDef, Contract, Field, Object, Pattern, Ty, Unknown, Uses, variant_name,
};

/// biome.json's `lineWidth`.
const TS_LINE_WIDTH: usize = 100;

pub(super) fn header(source: &str) -> String {
    format!(
        "// @generated by `cargo xtask codegen` from {source}. Edit the contract, not this file.\n"
    )
}

fn schema_name(def: &str) -> String {
    let mut chars = def.chars();
    let first = chars.next().map(|c| c.to_ascii_lowercase()).into_iter();
    first.chain(chars).collect::<String>() + "Schema"
}

/// A JavaScript number literal for a finite f64: `0`, `1.5`, `-2`. Rust's
/// `Display` never uses an exponent and prints the exact decimal of the
/// value, which JavaScript reads back as the same double.
fn js_number(n: f64) -> String {
    format!("{n}")
}

/// A Rust f64 literal clippy pedantic accepts: the shortest round-trip form,
/// its long digit runs grouped by three.
pub(super) fn rust_float(n: f64) -> String {
    let text = format!("{n:?}");
    let (mantissa, exponent) = match text.split_once('e') {
        Some((m, e)) => (m.to_owned(), format!("e{e}")),
        None => (text, String::new()),
    };
    let (sign, unsigned) = mantissa.strip_prefix('-').map_or(("", mantissa.as_str()), |m| ("-", m));
    let (int, frac) = unsigned.split_once('.').unwrap_or((unsigned, ""));
    let group = |digits: &str, from_left: bool| -> String {
        if digits.len() < 5 {
            return digits.to_owned();
        }
        let chars: Vec<char> = digits.chars().collect();
        let chunks: Vec<String> = if from_left {
            chars.chunks(3).map(|c| c.iter().collect()).collect()
        } else {
            let mut rev: Vec<String> =
                chars.rchunks(3).map(|c| c.iter().collect::<String>()).collect();
            rev.reverse();
            rev
        };
        chunks.join("_")
    };
    let frac = if frac.is_empty() { String::new() } else { format!(".{}", group(frac, true)) };
    format!("{sign}{}{frac}{exponent}", group(int, false))
}

/// `camelCase` of a `snake_case` name.
pub(super) fn camel(snake: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for c in snake.chars() {
        if c == '_' {
            upper = true;
        } else if upper {
            out.push(c.to_ascii_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

/// One call of a chain, `.name(arg, ..)`.
struct Call {
    name: &'static str,
    args: Vec<String>,
}

impl Call {
    fn flat(&self) -> String {
        format!(".{}({})", self.name, self.args.join(", "))
    }
}

/// A Zod expression as the chain it is written in: a head and its calls.
struct Chain {
    head: String,
    calls: Vec<Call>,
}

impl Chain {
    fn new(name: &'static str, args: Vec<String>) -> Self {
        Self { head: "z".to_owned(), calls: vec![Call { name, args }] }
    }

    fn named(name: String) -> Self {
        Self { head: name, calls: Vec::new() }
    }

    fn then(mut self, name: &'static str, args: Vec<String>) -> Self {
        self.calls.push(Call { name, args });
        self
    }

    /// One line when it fits `width`, else one call per line and a call whose
    /// line is still too long one argument per line, the way biome breaks a
    /// member chain; a chain of a single call keeps it on the head's line and
    /// breaks only its arguments.
    fn render(&self, indent: usize, lead: &str, trail: &str) -> String {
        let pad = " ".repeat(indent);
        let flat = format!(
            "{pad}{lead}{}{}{trail}",
            self.head,
            self.calls.iter().map(Call::flat).collect::<String>()
        );
        if flat.chars().count() <= TS_LINE_WIDTH || self.calls.is_empty() {
            return flat;
        }
        if let [call] = self.calls.as_slice() {
            let mut out = format!("{pad}{lead}{}.{}(", self.head, call.name);
            for arg in &call.args {
                let _ = write!(out, "\n{pad}  {arg},");
            }
            let _ = write!(out, "\n{pad}){trail}");
            return out;
        }
        let mut out = format!("{pad}{lead}{}", self.head);
        for call in &self.calls {
            let line = format!("{pad}  {}", call.flat());
            if line.chars().count() <= TS_LINE_WIDTH || call.args.is_empty() {
                let _ = write!(out, "\n{line}");
            } else {
                let _ = write!(out, "\n{pad}  .{}(", call.name);
                for arg in &call.args {
                    let _ = write!(out, "\n{pad}    {arg},");
                }
                let _ = write!(out, "\n{pad}  )");
            }
        }
        out.push_str(trail);
        out
    }
}

fn js_string(text: &str) -> String {
    format!("'{text}'")
}

fn zod_chain(ty: &Ty<'_>) -> Chain {
    let refine = |chain: Chain, check: Option<&str>| match check {
        Some(c) => chain.then("superRefine", vec![camel(c)]),
        None => chain,
    };
    match ty {
        Ty::Str { min_utf16, pattern, check } => {
            let mut chain = Chain::new("string", vec![]);
            if let Some(n) = min_utf16 {
                chain = chain.then("min", vec![n.to_string()]);
            }
            if let Some(Pattern { source, message, .. }) = pattern {
                chain = chain.then("regex", vec![format!("/{source}/"), js_string(message)]);
            }
            refine(chain, *check)
        }
        Ty::Array { item, min, max } => {
            let mut chain = Chain::new("array", vec![zod_chain(item).render(0, "", "")]);
            if let Some(n) = min {
                chain = chain.then("min", vec![n.to_string()]);
            }
            if let Some(n) = max {
                chain = chain.then("max", vec![n.to_string()]);
            }
            chain
        }
        Ty::Record { check } => refine(
            Chain::new("record", vec!["z.string()".to_owned(), "z.unknown()".to_owned()]),
            *check,
        ),
        other => zod_plain_chain(other),
    }
}

/// The forms with nothing to chain after them.
fn zod_plain_chain(ty: &Ty<'_>) -> Chain {
    match ty {
        Ty::Bool => Chain::new("boolean", vec![]),
        Ty::Integer => Chain::new("number", vec![])
            .then("int", vec![])
            .then("meta", vec!["{ minimum: undefined, maximum: undefined }".to_owned()]),
        Ty::Literal(value) => Chain::new("literal", vec![js_string(value)]),
        Ty::Number { min } => {
            let chain = Chain::new("number", vec![]);
            match min {
                Some(m) => chain.then("min", vec![js_number(*m)]),
                None => chain,
            }
        }
        Ty::Enum(values) => {
            let list: Vec<String> = values.iter().map(|v| js_string(v)).collect();
            Chain::new("enum", vec![format!("[{}]", list.join(", "))])
        }
        Ty::Union { members, discriminator } => {
            let list: Vec<String> = members.iter().map(|m| schema_name(m)).collect();
            let list = format!("[{}]", list.join(", "));
            match discriminator {
                Some(property) => Chain::new("discriminatedUnion", vec![js_string(property), list]),
                None => Chain::new("union", vec![list]),
            }
        }
        Ty::Ref(name) => Chain::named(schema_name(name)),
        Ty::Any => Chain::new("unknown", vec![]),
        Ty::Object(_) | Ty::Str { .. } | Ty::Array { .. } | Ty::Record { .. } => {
            Chain::named("z.object".to_owned())
        }
    }
}

fn zod_field(field: &Field<'_>, indent: usize, describe: bool) -> String {
    let mut chain = zod_chain(&field.ty);
    if field.default_empty {
        chain = chain.then("default", vec!["[]".to_owned()]);
    } else if field.optional {
        chain = chain.then("optional", vec![]);
    }
    if field.lenient {
        chain = chain.then("catch", vec!["undefined".to_owned()]);
    }
    if describe {
        chain = chain.then("describe", vec![js_string(field.description)]);
    } else if let Some(text) = field.published {
        chain = chain.then("describe", vec![js_string(text)]);
    }
    chain.render(indent, &format!("{}: ", field.name), ",")
}

/// An object as the chain biome keeps for one that is described, refined or
/// extended, and as a bare constructor call otherwise.
fn zod_object(
    out: &mut String,
    schema: &str,
    description: &str,
    object: &Object<'_>,
    describe: bool,
) {
    let ctor = match object.unknown {
        Unknown::Refuse => "strictObject",
        Unknown::Strip => "object",
        Unknown::Keep => "looseObject",
    };
    if !describe && object.check.is_none() && object.extends.is_none() {
        let _ = writeln!(out, "export const {schema} = z.{ctor}({{");
        for field in &object.fields {
            let _ = writeln!(out, "{}", zod_field(field, 2, false));
        }
        out.push_str("})\n");
        return;
    }
    match object.extends {
        Some(base) => {
            let _ = writeln!(out, "export const {schema} = {}\n  .extend({{", schema_name(base));
        }
        None => {
            let _ = writeln!(out, "export const {schema} = z\n  .{ctor}({{");
        }
    }
    for field in &object.fields {
        let _ = writeln!(out, "{}", zod_field(field, 4, describe));
    }
    out.push_str("  })\n");
    if object.extends.is_some() {
        out.push_str("  .strict()\n");
    }
    if describe {
        let _ = writeln!(out, "  .describe({})", js_string(description));
    }
    if let Some(check) = object.check {
        let _ = writeln!(out, "  .superRefine({})", camel(check));
    }
}

/// The import lines after `zod`'s own: the check module and each external
/// definition's, grouped by module, nearest-last the way biome sorts them and
/// each module's names in order.
fn zod_imports(checked: &Checked<'_>) -> String {
    let mut modules: BTreeMap<(bool, String), BTreeSet<String>> = BTreeMap::new();
    let mut add = |module: &str, name: String| {
        let sibling = module.starts_with("./");
        modules.entry((sibling, module.to_owned())).or_default().insert(name);
    };
    if let Some(found) = checked.contract.checks.as_ref().filter(|_| !checked.zod_checks.is_empty())
    {
        let stem = found.zod.rsplit('/').next().and_then(|f| f.strip_suffix(".ts")).unwrap_or("");
        for check in &checked.zod_checks {
            add(&format!("../{stem}.js"), camel(check));
        }
    }
    for def in &checked.defs {
        if let Some(module) = def.external {
            add(module, schema_name(def.name));
        }
    }
    let mut out = String::new();
    for ((_, module), names) in &modules {
        let list: Vec<&str> = names.iter().map(String::as_str).collect();
        let flat = format!("import {{ {} }} from '{module}'", list.join(", "));
        if flat.chars().count() <= TS_LINE_WIDTH {
            let _ = writeln!(out, "{flat}");
            continue;
        }
        out.push_str("import {\n");
        for name in list {
            let _ = writeln!(out, "  {name},");
        }
        let _ = writeln!(out, "}} from '{module}'");
    }
    out
}

fn zod_def(out: &mut String, contract: &Contract, def: &CheckedDef<'_>) {
    let CheckedDef { name, description, registered, ty, .. } = def;
    let schema = schema_name(name);
    let _ = write!(out, "\n/** {description} */\n");
    match ty {
        Ty::Object(object) => zod_object(out, &schema, description, object, contract.describe),
        other => {
            let mut chain = zod_chain(other);
            if contract.describe {
                chain = chain.then("describe", vec![js_string(description)]);
            }
            let _ = writeln!(out, "{}", chain.render(0, &format!("export const {schema} = "), ""));
        }
    }
    if *registered {
        let _ = writeln!(out, "z.globalRegistry.add({schema}, {{ id: '{name}' }})");
    }
    let infer = format!("z.infer<typeof {schema}>");
    let _ = if contract.readonly_types {
        writeln!(out, "export type {name} = Readonly<{infer}>")
    } else {
        writeln!(out, "export type {name} = {infer}")
    };
}

pub(super) fn zod(checked: &Checked<'_>, source: &str) -> Result<String, Vec<String>> {
    let mut out = header(source);
    out.push_str("\nimport { z } from 'zod'\n");
    out.push_str(&zod_imports(checked));
    for def in checked.defs.iter().filter(|d| d.external.is_none()) {
        zod_def(&mut out, checked.contract, def);
    }
    within_width(out)
}

/// A line holding only a string literal and its comma, which biome leaves as
/// long as the string is: there is nowhere in it to break.
fn lone_string(line: &str) -> bool {
    line.trim_start().strip_prefix('\'').is_some_and(|rest| rest.ends_with("',"))
}

/// `out` when every line after its header fits biome's width: a longer line
/// is refused rather than emitted, since biome would rewrap it.
pub(super) fn within_width(out: String) -> Result<String, Vec<String>> {
    let long: Vec<String> = out
        .lines()
        .skip(1)
        .filter(|line| line.chars().count() > TS_LINE_WIDTH && !lone_string(line))
        .map(|line| format!("a line past biome's {TS_LINE_WIDTH} columns; shorten it: {line}"))
        .collect();
    if long.is_empty() { Ok(out) } else { Err(long) }
}

const RUST_PRELUDE: &str = "
use std::marker::PhantomData;

use serde::de::value::MapAccessDeserializer;
use serde::de::{Deserializer, MapAccess, Visitor};
use serde::{Deserialize, Serialize};

/// Reads a JSON object and nothing else: a derived `Deserialize` also takes an
/// array in field order, which the Zod half refuses.
struct MapOnly<W>(PhantomData<W>);

impl<'de, W: Deserialize<'de>> Visitor<'de> for MapOnly<W> {
    type Value = W;

    fn expecting(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(\"an object\")
    }

    fn visit_map<A: MapAccess<'de>>(self, map: A) -> Result<W, A::Error> {
        W::deserialize(MapAccessDeserializer::new(map))
    }
}
";

pub(super) fn rust(checked: &Checked<'_>, source: &str) -> String {
    let mut out = header(source);
    let _ = writeln!(out, "\n//! {}", checked.contract.description);
    if checked.contract.rust_serde {
        out.push_str(RUST_PRELUDE);
        for def in &checked.defs {
            if let Ty::Object(object) = &def.ty {
                rust_serde_type(&mut out, def.name, def.description, object);
            }
        }
        return out;
    }
    let uses = |wanted| checked.defs.iter().any(|d| d.ty.uses(wanted));
    match (uses(Uses::Map), uses(Uses::Value)) {
        (true, true) => out.push_str("\nuse crate::{Map, Value};\n"),
        (true, false) => out.push_str("\nuse crate::Map;\n"),
        (false, true) => out.push_str("\nuse crate::Value;\n"),
        (false, false) => {}
    }
    for def in &checked.defs {
        rust_plain_type(&mut out, def, &checked.defs);
    }
    out
}

fn rust_ty(ty: &Ty<'_>) -> String {
    match ty {
        Ty::Number { .. } => "f64".to_owned(),
        Ty::Bool => "bool".to_owned(),
        Ty::Integer => "i64".to_owned(),
        Ty::Str { .. } => "String".to_owned(),
        Ty::Array { item, .. } => format!("Vec<{}>", rust_ty(item)),
        Ty::Ref(name) => (*name).to_owned(),
        Ty::Any => "Value".to_owned(),
        Ty::Record { .. } => "Map".to_owned(),
        Ty::Object(_) | Ty::Enum(_) | Ty::Union { .. } | Ty::Literal(_) => String::new(),
    }
}

/// The doc lines that point at the hand-written predicates standing behind a
/// type the schema alone cannot state.
fn rust_checked_by(ty: &Ty<'_>, indent: &str) -> String {
    let mut out = String::new();
    let (check, matcher) = match ty {
        Ty::Str { check, pattern, .. } => (*check, pattern.as_ref().map(|p| p.matcher)),
        Ty::Record { check } => (*check, None),
        Ty::Object(object) => (object.check, None),
        Ty::Array { item, .. } => return rust_checked_by(item, indent),
        _ => (None, None),
    };
    for (verb, name) in [("Matched", matcher), ("Checked", check)] {
        if let Some(name) = name {
            let _ = writeln!(out, "{indent}///\n{indent}/// {verb} by `crate::checks::{name}`.");
        }
    }
    out
}

fn rust_plain_type(
    out: &mut String,
    CheckedDef { name, description, ty, .. }: &CheckedDef<'_>,
    defs: &[CheckedDef<'_>],
) {
    let object = match ty {
        Ty::Object(object) => object,
        Ty::Enum(values) => return rust_enum(out, name, description, values),
        Ty::Union { members, .. } => return rust_union(out, name, description, members),
        _ => {
            let _ = write!(out, "\n/// {description}\n{}", rust_checked_by(ty, ""));
            let _ = writeln!(out, "pub type {name} = {};", rust_ty(ty));
            return;
        }
    };
    let _ = write!(
        out,
        "\n/// {description}\n{}#[derive(Debug, Clone, PartialEq, Default)]\npub struct {name} {{\n",
        rust_checked_by(ty, "")
    );
    let inherited = object
        .extends
        .and_then(|base| defs.iter().find(|d| d.name == base))
        .into_iter()
        .filter_map(|d| if let Ty::Object(o) = &d.ty { Some(o.fields.iter()) } else { None })
        .flatten();
    let all: Vec<&Field<'_>> = inherited.chain(&object.fields).collect();
    for field in &all {
        rust_field(out, field);
    }
    if object.unknown == Unknown::Keep {
        out.push_str(
            "    /// Keys the contract does not name, in the order written.\n    pub extra: Map,\n",
        );
    }
    out.push_str("}\n");
    rust_constants(out, name, &all);
}

/// One struct field, or nothing for a constant, which is the type's own.
fn rust_field(out: &mut String, field: &Field<'_>) {
    if matches!(field.ty, Ty::Literal(_)) {
        return;
    }
    let inner = rust_ty(&field.ty);
    let wrapped =
        if field.optional && !field.default_empty { format!("Option<{inner}>") } else { inner };
    let _ = write!(out, "    /// {}\n{}", field.description, rust_checked_by(&field.ty, "    "));
    if field.lenient {
        out.push_str("    ///\n    /// A malformed value reads as absent.\n");
    }
    let _ = writeln!(out, "    pub {}: {wrapped},", field.rust);
}

/// The constants of a struct, one for each property that is always one value.
fn rust_constants(out: &mut String, name: &str, fields: &[&Field<'_>]) {
    let constants: Vec<(&Field<'_>, &str)> = fields
        .iter()
        .filter_map(|f| if let Ty::Literal(value) = f.ty { Some((*f, value)) } else { None })
        .collect();
    if constants.is_empty() {
        return;
    }
    let _ = writeln!(out, "\nimpl {name} {{");
    for (field, value) in constants {
        let constant = field.rust.trim_start_matches("r#").to_ascii_uppercase();
        let _ = writeln!(
            out,
            "    /// What `{}` is always written as.\n    pub const {constant}: &str = \"{value}\";",
            field.name
        );
    }
    out.push_str("}\n");
}

fn rust_serde_type(out: &mut String, name: &str, description: &str, object: &Object<'_>) {
    let fields: Vec<(&str, Option<f64>)> = object
        .fields
        .iter()
        .map(|f| (f.name, if let Ty::Number { min } = f.ty { min } else { None }))
        .collect();
    let docs: Vec<&str> = object.fields.iter().map(|f| f.description).collect();
    let _ = write!(
        out,
        "\n/// {description}\n#[derive(Debug, Clone, Copy, PartialEq, Serialize)]\npub struct {name} {{\n"
    );
    for ((field, _), doc) in fields.iter().zip(&docs) {
        let _ = writeln!(out, "    /// {doc}\n    pub {field}: f64,");
    }
    let _ = write!(
        out,
        "}}\n\n/// `{name}` as it arrives, before it is checked.\n\
         #[derive(Deserialize)]\n#[serde(deny_unknown_fields)]\nstruct {name}Wire {{\n"
    );
    for (field, _) in &fields {
        let _ = writeln!(out, "    {field}: f64,");
    }
    let _ = write!(
        out,
        "}}\n\nimpl<'de> Deserialize<'de> for {name} {{\n\
         fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {{\n\
         let wire: {name}Wire = deserializer.deserialize_map(MapOnly(PhantomData))?;\n"
    );
    for (field, minimum) in &fields {
        if let Some(min) = minimum {
            let _ = write!(
                out,
                "if wire.{field}.is_nan() || wire.{field} < {} {{\n\
                 return Err(serde::de::Error::custom(\"{name}.{field} is below its minimum {}\"));\n}}\n",
                rust_float(*min),
                js_number(*min)
            );
        }
    }
    let names: Vec<String> = fields.iter().map(|(f, _)| format!("{f}: wire.{f}")).collect();
    let _ = write!(out, "Ok(Self {{ {} }})\n}}\n}}\n", names.join(", "));
}

/// A closed set of strings as a Rust enum whose first value is its `Default`,
/// so a struct holding one can still derive it.
fn rust_enum(out: &mut String, name: &str, description: &str, values: &[&str]) {
    let variants: Vec<String> = values.iter().map(|v| variant_name(v)).collect();
    let _ = write!(
        out,
        "\n/// {description}\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]\npub enum {name} {{\n"
    );
    for (i, (variant, value)) in variants.iter().zip(values).enumerate() {
        let default = if i == 0 { "    #[default]\n" } else { "" };
        let _ = writeln!(out, "    /// Written `{value}`.\n{default}    {variant},");
    }
    let _ = write!(out, "}}\n\nimpl {name} {{\n    /// The value as the contract writes it.\n");
    out.push_str("    pub const fn as_str(self) -> &'static str {\n        match self {\n");
    for (variant, value) in variants.iter().zip(values) {
        let _ = writeln!(out, "            Self::{variant} => \"{value}\",");
    }
    out.push_str(
        "        }\n    }\n\n    /// The variant a written value names, if any.\n    \
         pub fn from_wire(text: &str) -> Option<Self> {\n        match text {\n",
    );
    for (variant, value) in variants.iter().zip(values) {
        let _ = writeln!(out, "            \"{value}\" => Some(Self::{variant}),");
    }
    out.push_str("            _ => None,\n        }\n    }\n}\n");
}

/// One of several definitions as a Rust enum of the types it names, the first
/// member's `Default` standing for its own.
fn rust_union(out: &mut String, name: &str, description: &str, members: &[&str]) {
    let _ = write!(
        out,
        "\n/// {description}\n#[derive(Debug, Clone, PartialEq)]\npub enum {name} {{\n"
    );
    for member in members {
        let _ = writeln!(out, "    /// A `{member}`.\n    {member}({member}),");
    }
    let first = members.first().copied().unwrap_or_default();
    let _ = write!(
        out,
        "}}\n\nimpl Default for {name} {{\n    fn default() -> Self {{\n        \
         Self::{first}({first}::default())\n    }}\n}}\n"
    );
}
