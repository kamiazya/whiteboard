//! The two emitters, one walk of a checked contract each.
//!
//! What each construct means is written here side by side for both
//! languages: a bound is `.min()` in Zod and a check in the Rust type's
//! `Deserialize`; `refuse` is `z.strictObject` and `deny_unknown_fields`.
//! The Rust half reads through `MapOnly` because serde's derived
//! `Deserialize` also accepts a JSON array in field order, which
//! `z.strictObject` refuses.
//!
//! The Rust text is unformatted; `mod.rs` runs it through rustfmt. The Zod
//! text is written in the shape biome keeps, and a line past biome's width
//! is refused rather than emitted.

use std::fmt::Write as _;

use super::dialect::{Checked, CheckedDef};

/// biome.json's `lineWidth`.
const TS_LINE_WIDTH: usize = 100;

pub(super) fn header(source: &str) -> String {
    format!(
        "// @generated by `cargo xtask codegen` from {source}. Edit the contract, not this file.\n"
    )
}

fn schema_name(def: &str) -> String {
    let mut chars = def.chars();
    let first = chars.next().map(|c| c.to_ascii_lowercase()).into_iter();
    first.chain(chars).collect::<String>() + "Schema"
}

/// A JavaScript number literal for a finite f64: `0`, `1.5`, `-2`. Rust's
/// `Display` never uses an exponent and prints the exact decimal of the
/// value, which JavaScript reads back as the same double.
fn js_number(n: f64) -> String {
    format!("{n}")
}

/// A Rust f64 literal clippy pedantic accepts: the shortest round-trip form,
/// its long digit runs grouped by three.
pub(super) fn rust_float(n: f64) -> String {
    let text = format!("{n:?}");
    let (mantissa, exponent) = match text.split_once('e') {
        Some((m, e)) => (m.to_owned(), format!("e{e}")),
        None => (text, String::new()),
    };
    let (sign, unsigned) = mantissa.strip_prefix('-').map_or(("", mantissa.as_str()), |m| ("-", m));
    let (int, frac) = unsigned.split_once('.').unwrap_or((unsigned, ""));
    let group = |digits: &str, from_left: bool| -> String {
        if digits.len() < 5 {
            return digits.to_owned();
        }
        let chars: Vec<char> = digits.chars().collect();
        let chunks: Vec<String> = if from_left {
            chars.chunks(3).map(|c| c.iter().collect()).collect()
        } else {
            let mut rev: Vec<String> =
                chars.rchunks(3).map(|c| c.iter().collect::<String>()).collect();
            rev.reverse();
            rev
        };
        chunks.join("_")
    };
    let frac = if frac.is_empty() { String::new() } else { format!(".{}", group(frac, true)) };
    format!("{sign}{}{frac}{exponent}", group(int, false))
}

pub(super) fn zod(checked: &Checked<'_>, source: &str) -> Result<String, Vec<String>> {
    let mut out = header(source);
    out.push_str("\nimport { z } from 'zod'\n");
    for CheckedDef { name, def, fields } in &checked.defs {
        let schema = schema_name(name);
        let _ = write!(
            out,
            "\n/** {} */\nexport const {schema} = z\n  .strictObject({{\n",
            def.description
        );
        for (field, property) in fields {
            let min =
                property.minimum.map(|m| format!(".min({})", js_number(m))).unwrap_or_default();
            let _ =
                writeln!(out, "    {field}: z.number(){min}.describe('{}'),", property.description);
        }
        let _ = write!(
            out,
            "  }})\n  .describe('{}')\nexport type {name} = Readonly<z.infer<typeof {schema}>>\n",
            def.description
        );
    }
    let long: Vec<String> = out
        .lines()
        .skip(1)
        .filter(|line| line.chars().count() > TS_LINE_WIDTH)
        .map(|line| format!("a line past biome's {TS_LINE_WIDTH} columns; shorten it: {line}"))
        .collect();
    if long.is_empty() { Ok(out) } else { Err(long) }
}

const RUST_PRELUDE: &str = "
use std::marker::PhantomData;

use serde::de::value::MapAccessDeserializer;
use serde::de::{Deserializer, MapAccess, Visitor};
use serde::{Deserialize, Serialize};

/// Reads a JSON object and nothing else: a derived `Deserialize` also takes an
/// array in field order, which the Zod half refuses.
struct MapOnly<W>(PhantomData<W>);

impl<'de, W: Deserialize<'de>> Visitor<'de> for MapOnly<W> {
    type Value = W;

    fn expecting(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(\"an object\")
    }

    fn visit_map<A: MapAccess<'de>>(self, map: A) -> Result<W, A::Error> {
        W::deserialize(MapAccessDeserializer::new(map))
    }
}
";

pub(super) fn rust(checked: &Checked<'_>, source: &str) -> String {
    let mut out = header(source);
    let _ = writeln!(out, "\n//! {}", checked.contract.description);
    out.push_str(RUST_PRELUDE);
    for def in &checked.defs {
        rust_type(&mut out, def);
    }
    out
}

fn rust_type(out: &mut String, CheckedDef { name, def, fields }: &CheckedDef<'_>) {
    let _ = write!(
        out,
        "\n/// {}\n#[derive(Debug, Clone, Copy, PartialEq, Serialize)]\npub struct {name} {{\n",
        def.description
    );
    for (field, property) in fields {
        let _ = writeln!(out, "    /// {}\n    pub {field}: f64,", property.description);
    }
    let _ = write!(
        out,
        "}}\n\n/// `{name}` as it arrives, before it is checked.\n\
         #[derive(Deserialize)]\n#[serde(deny_unknown_fields)]\nstruct {name}Wire {{\n"
    );
    for (field, _) in fields {
        let _ = writeln!(out, "    {field}: f64,");
    }
    let _ = write!(
        out,
        "}}\n\nimpl<'de> Deserialize<'de> for {name} {{\n\
         fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {{\n\
         let wire: {name}Wire = deserializer.deserialize_map(MapOnly(PhantomData))?;\n"
    );
    for (field, property) in fields {
        if let Some(min) = property.minimum {
            let _ = write!(
                out,
                "if wire.{field}.is_nan() || wire.{field} < {} {{\n\
                 return Err(serde::de::Error::custom(\"{name}.{field} is below its minimum {}\"));\n}}\n",
                rust_float(min),
                js_number(min)
            );
        }
    }
    let names: Vec<String> = fields.iter().map(|(f, _)| format!("{f}: wire.{f}")).collect();
    let _ = write!(out, "Ok(Self {{ {} }})\n}}\n}}\n", names.join(", "));
}
