import { spawnSync } from 'node:child_process'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { REPO_ROOT } from './scan-roots.js'

/**
 * The line breaker's class table in the Rust core is generated from
 * `css-line-break`'s trie, which only a Node script can read. The Rust replay
 * (`tests/linebreak_oracle.rs`) already holds the table to the trie by digest;
 * this is the other direction, that the committed file is byte-for-byte what
 * the script writes, so a hand edit or a stale regeneration is named as such
 * rather than as 272 differing digests.
 */
const SCRIPT = join(REPO_ROOT, 'packages/canvas-render/scripts/gen-linebreak-table.mjs')
const TABLE = join(REPO_ROOT, 'crates/core/canvas-render/src/linebreak/table.rs')

describe('the line-break class table of the Rust core', () => {
  it('is what the generator writes from the installed css-line-break', () => {
    const run = spawnSync(process.execPath, [SCRIPT, '--check', TABLE], { encoding: 'utf8' })
    expect(
      run.status,
      `${run.stderr}\nregenerate: node packages/canvas-render/scripts/gen-linebreak-table.mjs crates/core/canvas-render/src/linebreak/table.rs`,
    ).toBe(0)
  })

  it('is marked generated, so nobody edits it', () => {
    const run = spawnSync('head', ['-n', '1', TABLE], { encoding: 'utf8' })
    expect(run.stdout).toMatch(/^\/\/ @generated by /)
  })
})
