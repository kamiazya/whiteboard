import { spawnSync } from 'node:child_process'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { REPO_ROOT } from './scan-roots.js'

/**
 * The phrase breaker's model tables in the Rust core are generated from the
 * vendored BudouX model, which only a Node script can read. The Rust replay
 * (`tests/budoux_oracle.rs`) already holds the tables to the TypeScript's
 * answers; this is the other direction, that the committed file is
 * byte-for-byte what the script writes, so a hand edit or a stale
 * regeneration is named as such rather than as a thousand differing answers.
 */
const SCRIPT = join(REPO_ROOT, 'packages/canvas-render/scripts/gen-budoux-model.mjs')
const MODEL = join(REPO_ROOT, 'crates/core/canvas-render/src/budoux/model.rs')

describe('the BudouX model tables of the Rust core', () => {
  it('are what the generator writes from the vendored model', () => {
    const run = spawnSync(process.execPath, [SCRIPT, '--check', MODEL], { encoding: 'utf8' })
    expect(
      run.status,
      `${run.stderr}\nregenerate: node packages/canvas-render/scripts/gen-budoux-model.mjs crates/core/canvas-render/src/budoux/model.rs`,
    ).toBe(0)
  })

  it('are marked generated, so nobody edits them', () => {
    const run = spawnSync('head', ['-n', '1', MODEL], { encoding: 'utf8' })
    expect(run.stdout).toMatch(/^\/\/ @generated by /)
  })
})
